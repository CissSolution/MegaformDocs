#!/usr/bin/env node
// ============================================================
// [KbPerTemplate v20260812] Derive a template's AI-knowledge payload FROM the
// template document itself.
//
// The owner's rule: a template's KB travels WITH the template (downloaded from
// the gallery), it does not ship inside the module package. This module is the
// deterministic half of that — given one template JSON it produces exactly the
// KB rows that template needs, so the gallery can publish 68/68 instead of the
// 13 that happened to be hand-seeded.
//
// Two KB rows per template, and they must live in SEPARATE slug namespaces:
//
//   Kind='form_template'   slug "gallery-<slug>"  — the CREATE corpus. The AI
//       finds it with list_knowledge(kind="form_template", search=…) and applies
//       Examples[0] (a replace_form_schema op) verbatim. Body carries the template
//       document WITHOUT customHtml/customCss: the create flow wants the schema,
//       not the design shell (matches the 178 entries already in the seed).
//
//   Kind='template_guide'  slug "tpl-<slug>"       — the REFINE contract, read by
//       get_template_guide(slug). Body is {"guide_file": "<slug>.guide.md"} and the
//       markdown itself is shipped as a resource.
//
// WHY TWO NAMESPACES: AiKnowledgeRepository.Upsert keys on Slug ALONE
// (MegaForm.DNN/Data/AiKnowledgeRepository.cs:71 `WHERE Slug = @Slug`), so one
// slug can hold exactly one row of one Kind. Putting both kinds on "tpl-<slug>"
// is not a naming preference, it is a data collision: whichever is merged last
// wins and the other lookup starts failing. Measured on the shipped seed today:
// 13 gallery templates own tpl-<slug> as form_template, 10 own it as
// template_guide, and the overlap is exactly ZERO — not a coincidence, an
// invariant of the primary key.
//
// "tpl-<slug>" is left to the GUIDE because 24 published templates already point
// at it through settings.templateGuideSlug and three Oqtane migrations already
// seeded guide rows there; moving that namespace would break live data, while
// the form_template slug is only ever reached through a search result.
//
// Pure + deterministic: no network, no clock, no AI. Same input → same bytes,
// which is what lets build-gallery.mjs pin a sha256 that stays stable across runs.
// ============================================================
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

/** Slug of the CREATE-corpus row (Kind='form_template'). */
export const formTemplateSlug = (slug) => 'gallery-' + slug;
/** Slug of the REFINE-contract row (Kind='template_guide') — the namespace
 *  settings.templateGuideSlug already points at. */
export const templateGuideSlug = (slug) => 'tpl-' + slug;

/**
 * Flatten fields the way the shipped corpus counts them: a Row contributes
 * ITSELF plus its column children, because customHtml carries one
 * {{field:rowKey}} token that expands both columns. Verified against the seed —
 * "fields:N" in Tags matches this count exactly on every gallery entry measured
 * (halloween 12, pure-grid 24, celebration-rsvp 9).
 */
export function flattenFields(fields, out = []) {
  for (const f of fields || []) {
    if (!f) continue;
    out.push(f);
    if (Array.isArray(f.columns)) {
      for (const c of f.columns) flattenFields(c?.fields || [], out);
    }
  }
  return out;
}

/** Distinct field types in order of first appearance (the corpus's ordering). */
function distinctTypes(flat) {
  const seen = [];
  for (const f of flat) {
    const t = String(f?.type || '').trim();
    if (t && !seen.includes(t)) seen.push(t);
  }
  return seen;
}

/**
 * Tags: "form_template,<category>,<category with spaces>,fields:N,has-row,type-*"
 * — the first FIVE types only, matching the shipped entries.
 */
export function deriveTags(doc, flat) {
  const category = String(doc.category || 'general').trim();
  const spaced = category.replace(/-/g, ' ');
  const types = distinctTypes(flat);
  // The spaced variant is emitted even when it is identical to the category —
  // the shipped entries read "…,automotive,automotive,…", so a dedup here would
  // make regenerated tags disagree with the corpus for every single-word category.
  const tags = ['form_template', category, spaced];
  tags.push('fields:' + flat.length);
  if (flat.some((f) => f?.type === 'Row')) tags.push('has-row');
  if (doc.settings && doc.settings.multiPage === true) tags.push('multi-page');
  for (const t of types.slice(0, 5)) tags.push('type-' + t.toLowerCase());
  return tags.join(',');
}

/**
 * Summary: "<description> [Category: <category> · N fields · uses: T1, T2, …]"
 * — the first SIX types. Note the REAL "·" (U+00B7): every one of the 178
 * shipped entries carries "Â·" instead, mojibake from the sqlcmd export that
 * produced ai-knowledge-seed.json. Generated bytes are clean UTF-8.
 */
export function deriveSummary(doc, flat) {
  const description = String(doc.description || '').trim();
  const category = String(doc.category || 'general').trim();
  const uses = distinctTypes(flat).slice(0, 6).join(', ');
  const multiPage = doc.settings && doc.settings.multiPage === true;
  const facts = 'Category: ' + category + ' · ' + flat.length + ' fields'
    + (multiPage ? ' · multi-page' : '')
    + (uses ? ' · uses: ' + uses : '');
  return (description ? description + ' ' : '') + '[' + facts + ']';
}

/**
 * The create-flow Body: the template document minus the design shell. customHtml
 * and customCss are what make the file big (and what the AI must NOT paste into a
 * new form), so they are dropped here — exactly what the shipped entries do.
 */
/**
 * The template's settings with the design shell removed. Both shapes exist in the published
 * set — some templates carry customHtml/customCss at the root, others inside settings — and the
 * ones that keep it in settings are why this matters: leaving it in multiplies the payload by
 * 10-40× (measured: median 54 KB, worst 220 KB, against the shipped corpus's 5.9 KB ceiling),
 * and the client trims any tool result past its budget, so an oversized op reaches the model cut
 * mid-JSON and cannot be applied at all.
 *
 * It is also wrong on the merits: the AI starts a NEW form from this schema. The premium shell
 * belongs to the template install, not to a schema the assistant pastes into someone else's form.
 */
const KEPT_SETTINGS = ['theme', 'multiPage', 'customContent'];

function settingsWithoutShell(doc) {
  // ALLOWLIST, not a blocklist. Measured on the 178 shipped entries, Body.settings only ever
  // holds these three (178× theme, 176× multiPage, 172× customContent) — so this reproduces the
  // corpus convention exactly, and it cannot be defeated the way a blocklist was: templates spell
  // the shell BOTH ways (`settings.customCss` and `settings.CustomCss`), and dropping only the
  // lowercase pair left a 43 KB stylesheet plus 15 KB of customScripts inside the op. That is how
  // a payload reaches 162 KB and gets cut to nothing by the client's result budget.
  const src = doc.settings || {};
  const out = {};
  for (const wanted of KEPT_SETTINGS) {
    const hit = Object.keys(src).find((k) => k.toLowerCase() === wanted.toLowerCase());
    if (hit !== undefined && src[hit] !== undefined) out[wanted] = src[hit];
  }
  return out;
}

export function stripDesignShell(doc) {
  const settings = settingsWithoutShell(doc);
  return {
    title: doc.title || '',
    description: doc.description || '',
    category: doc.category || 'general',
    icon: doc.icon || '',
    submitButtonText: doc.submitButtonText || '',
    successMessage: doc.successMessage || '',
    settings,
    fields: doc.fields || [],
  };
}

/** The op the AI applies verbatim to start from this template. */
export function buildExamples(doc) {
  return [{
    op: 'replace_form_schema',
    schema: {
      version: String(doc.version || '1.0'),
      fields: doc.fields || [],
      // Shell-free, exactly like Body — see settingsWithoutShell.
      settings: settingsWithoutShell(doc),
    },
  }];
}

/** One KB row, shaped for AiKnowledgeSeedMerger.Merge (PascalCase keys). */
function entryRow(o) {
  return {
    Slug: o.slug,
    Kind: o.kind,
    Title: o.title || '',
    Summary: o.summary || '',
    Body: o.body || '',
    Tags: o.tags || '',
    Examples: o.examples || '',
    PortalId: null,
    Source: 'megaform-builtin',
    WidgetType: '',
    Surface: '',
    Version: 1,
  };
}

/**
 * Build the whole KB payload for one template.
 *
 * @param {object}  opts.doc       parsed template JSON
 * @param {string}  opts.slug      canonical slug (from the document, already validated)
 * @param {string} [opts.guideDir] folder holding <slug>.guide.md / <slug>.facts.json
 * @returns {{entries: object[], resources: {name: string, data: Buffer}[], warnings: string[]}}
 */
export function buildTemplateKb({ doc, slug, guideDir }) {
  const warnings = [];
  const flat = flattenFields(doc.fields);

  // A container that nests fields OUTSIDE a Row (Section-style) would be counted
  // differently by the corpus convention above. Say so rather than publish a
  // field count that quietly disagrees with the form.
  for (const f of flat) {
    if (f && !Array.isArray(f.columns) && Array.isArray(f.fields) && f.fields.length) {
      warnings.push(`field "${f.key || f.type}" nests fields outside a Row — not counted in fields:N`);
    }
  }

  const entries = [entryRow({
    slug: formTemplateSlug(slug),
    kind: 'form_template',
    title: doc.title || slug,
    summary: deriveSummary(doc, flat),
    body: JSON.stringify(stripDesignShell(doc)),
    tags: deriveTags(doc, flat),
    examples: JSON.stringify(buildExamples(doc)),
  })];

  const resources = [];

  // The refine contract ships only when a guide actually exists on disk. A
  // template_guide row whose guide_file is missing resolves to the literal string
  // "[guide_file not found: …]" (AiToolsController.ResolveKnowledgeBody) — the AI
  // reads that as its design contract, which is worse than having no row at all.
  const guideName = slug + '.guide.md';
  const factsName = slug + '.facts.json';
  const guidePath = guideDir ? join(guideDir, guideName) : null;
  const legacyPath = guideDir ? join(guideDir, slug + '.md') : null;

  let guideFile = null;
  if (guidePath && existsSync(guidePath)) {
    guideFile = guideName;
    resources.push({ name: guideName, data: readFileSync(guidePath) });
  } else if (legacyPath && existsSync(legacyPath)) {
    // Pre-.guide.md naming, still referenced by the seeded rows for 6 templates.
    guideFile = slug + '.md';
    resources.push({ name: guideFile, data: readFileSync(legacyPath) });
  }

  if (guideFile) {
    entries.push(entryRow({
      slug: templateGuideSlug(slug),
      kind: 'template_guide',
      title: doc.title || slug,
      summary: String(doc.description || '').trim().slice(0, 300),
      body: JSON.stringify({ guide_file: guideFile }),
      tags: ['premium', 'template-guide', String(doc.category || 'general')].join(','),
    }));

    // facts.json is the deterministic field/token map the guide references. It is
    // read off disk beside the guide, so it must travel with it.
    const factsPath = join(guideDir, factsName);
    if (existsSync(factsPath)) resources.push({ name: factsName, data: readFileSync(factsPath) });
  } else {
    warnings.push('no guide file — template ships CREATE knowledge only, no refine contract');
  }

  // A pointer that resolves to nothing is the failure mode this whole exercise
  // exists to remove: measured on the shipped set, 20 of the 24 templates that
  // declare templateGuideSlug point at a row that does not exist, so
  // get_template_guide answers "not found" and the AI edits the premium shell blind.
  const declared = String(doc.templateGuideSlug || doc.TemplateGuideSlug
    || (doc.settings && doc.settings.templateGuideSlug) || '').trim();
  if (declared && guideFile && declared !== templateGuideSlug(slug)) {
    warnings.push(`templateGuideSlug "${declared}" does not match the published guide row "${templateGuideSlug(slug)}"`);
  }
  if (declared && !guideFile) {
    warnings.push(`declares templateGuideSlug "${declared}" but no guide file exists — the pointer is dead`);
  }

  return { entries, resources, warnings };
}

/** The seed-shaped document AiKnowledgeSeedMerger.Merge consumes as-is. */
export function toSeedDocument(entries) {
  return { entries, templates: [], rules: [] };
}
